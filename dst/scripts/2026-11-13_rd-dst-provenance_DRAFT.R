# RD DST: save the methods-page values that were printed but never written to a DATA file.
# Runs on firebreather inside jobs/rd_dst_engine_20261112. Aggregates only; no plot keys or locations leave.
suppressMessages(library(data.table))
setwd("~/jobs/rd_dst_engine_20261112")
x <- as.data.table(readRDS("dst_engine_input_DATA.rds"))
f <- as.data.table(readRDS("dst_natdist_flags_DATA.rds"))
w <- as.data.table(readRDS("dst_ipw_DATA.rds"))
out <- list()
add <- function(stat, region, value, source) out[[length(out) + 1]] <<- data.table(stat, region, value, source)
add("intervals", "All", nrow(x), "dst_engine_input_DATA.rds")
add("plots", "All", uniqueN(x$LOC), "dst_engine_input_DATA.rds")
stopifnot(nrow(f) == nrow(x))
xf <- merge(x[, .(pid, region)], f[, .(pid, dist_nat)], by = "pid")
add("natural_disturbance_share", "All", mean(xf$dist_nat), "dst_natdist_flags_DATA.rds dist_nat (codes 10 to 54), as engine v2")
add("original_any_code_flag_share", "All", mean(x$natdist == 1), "dst_engine_input_DATA.rds natdist (any DSTRBCD > 0)")
# Saved flags hold codes 10-54, 60, 70 and 90-95; code 80 (human) was not saved, so this union is a lower bound on the any-code flag.
anyc <- as.integer(f$dist_nat | f$dist_veg | f$dist_unk | f$dist_geo)
add("flag_rows_matched_to_condition_records", "All", sum(f$matched), "dst_natdist_flags_DATA.rds matched")
add("flag_union_agrees_with_original_share", "All", mean(anyc == f$natdist_old), "dst_natdist_flags_DATA.rds (union of saved codes)")
add("flag_union_agrees_with_original_n", "All", sum(anyc == f$natdist_old), "dst_natdist_flags_DATA.rds (union of saved codes)")
add("original_flag_set_union_not_set_n", "All", sum(f$natdist_old == 1 & anyc == 0), "dst_natdist_flags_DATA.rds (likely code 80 only)")
add("union_set_original_not_set_n", "All", sum(f$natdist_old == 0 & anyc == 1), "dst_natdist_flags_DATA.rds")
add("share_flagged_only_code60_or_70", "All", mean((f$dist_veg | f$dist_unk) & !f$dist_nat & !f$dist_geo), "dst_natdist_flags_DATA.rds")
for (r in c("North", "Central", "Southeast", "West")) {
  add("median_interval_length_yr", r, median(x[region == r, T]), "dst_engine_input_DATA.rds T")
  add("intervals", r, x[region == r, .N], "dst_engine_input_DATA.rds")
}
stopifnot(nrow(w) == nrow(x))
add("ipw_min", "All", min(w$ipw), "dst_ipw_DATA.rds"); add("ipw_max", "All", max(w$ipw), "dst_ipw_DATA.rds")
add("ipw_mean", "All", mean(w$ipw), "dst_ipw_DATA.rds")
# Values printed by the original runs (logged, not recomputed here)
lg <- readLines("run_v2_lag.log")
for (r in c("North", "Central", "Southeast", "West")) {
  v <- as.numeric(sub(".*R2 ", "", grep(paste0("^", r, " first stage R2"), lg, value = TRUE)))
  add("lag_first_stage_R2", r, v, "run_v2_lag.log (2026-11-12 engine v2 lag check)")
}
le <- grep("plots with public coordinates", readLines("run_v2_esi.log"), value = TRUE)
n_pub <- as.numeric(sub(" of.*", "", sub(".*coordinates ", "", le)))
add("plots_with_public_coordinates", "All", n_pub, "run_v2_esi.log (count only)")
add("share_plots_with_public_coordinates", "All", n_pub / uniqueN(x$LOC), "run_v2_esi.log / input")
res <- rbindlist(out)
dir.create("output_prov", showWarnings = FALSE)
fwrite(res, "output_prov/dst_engine2_provenance_DATA.csv")
print(res)
